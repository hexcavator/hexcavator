"""Generates crates/formats/elf/src/spelling.rs: the names llvm-readobj
prints for ELF's constants (machines, section and segment types, section
flags, dynamic tags, relocation types by machine), from LLVM's
BinaryFormat/ELF.h, DynamicTags.def, and ELFRelocs/*.def (Apache License
2.0 with LLVM Exceptions; see crates/formats/elf/LICENSE-LLVM).

    python -I tools/elf/names.py <llvm-project> > crates/formats/elf/src/spelling.rs
"""

import os
import re
import sys

# Relocation tables by machine: (EM_ names, .def file).
RELOCS = [
    (["EM_X86_64"], "x86_64.def"),
    (["EM_386", "EM_IAMCU"], "i386.def"),
    (["EM_AARCH64"], "AArch64.def"),
    (["EM_ARM"], "ARM.def"),
    (["EM_RISCV"], "RISCV.def"),
    (["EM_PPC64"], "PowerPC64.def"),
    (["EM_PPC"], "PowerPC.def"),
    (["EM_MIPS"], "Mips.def"),
    (["EM_S390"], "SystemZ.def"),
    (["EM_LOONGARCH"], "LoongArch.def"),
    (["EM_SPARC", "EM_SPARC32PLUS", "EM_SPARCV9"], "Sparc.def"),
    (["EM_HEXAGON"], "Hexagon.def"),
]

# Processor-specific section and segment types and dynamic tags, by the
# machine their prefix names.
PROCESSORS = {
    "ARM": ["EM_ARM"],
    "AARCH64": ["EM_AARCH64"],
    "MIPS": ["EM_MIPS"],
    "X86_64": ["EM_X86_64"],
    "RISCV": ["EM_RISCV"],
    "HEX": ["EM_HEXAGON"],
    "HEXAGON": ["EM_HEXAGON"],
    "MSP430": ["EM_MSP430"],
    "CSKY": ["EM_CSKY"],
    "PPC": ["EM_PPC"],
    "PPC64": ["EM_PPC64"],
}


def enum_entries(text, prefix):
    """`PREFIX_NAME = value,` entries of ELF.h, in order."""
    out = []
    for m in re.finditer(r"^\s*(%s[A-Za-z0-9_]+)\s*=\s*(0x[0-9A-Fa-f]+|\d+)U?\s*,?" % re.escape(prefix), text, re.M):
        out.append((m.group(1), int(m.group(2), 0)))
    return out


def main():
    root = sys.argv[1]
    inc = os.path.join(root, "llvm", "include", "llvm", "BinaryFormat")
    elf_h = open(os.path.join(inc, "ELF.h"), encoding="utf-8").read()
    elf_def = open(os.path.join(inc, "ELF.def"), encoding="utf-8").read()
    # Machines: ELF.def's ELF_MACHINE(EM_NAME, value, "arch", "description").
    machine_list = [(m.group(1), int(m.group(2), 0)) for m in re.finditer(r"^ELF_MACHINE\(\s*(EM_[A-Za-z0-9_]+)\s*,\s*(0x[0-9A-Fa-f]+|\d+)", elf_def, re.M)]
    machines = dict(machine_list)
    out = []
    w = out.append
    w("//! The names llvm-readobj gives ELF's constants, by group (and, for")
    w("//! processor-specific ones, machine).")
    w("//!")
    w("//! Generated by tools/elf/names.py from LLVM's BinaryFormat/ELF.h,")
    w("//! DynamicTags.def, and ELFRelocs/*.def (Apache License 2.0 with LLVM")
    w("//! Exceptions: see LICENSE-LLVM). Do not edit.")
    w("")
    w("#![allow(clippy::match_same_arms, clippy::too_many_lines)]")
    w("")
    w("use alloc::vec;")
    w("use alloc::vec::Vec;")
    w("")

    def emit(name, doc, entries, key="u64"):
        seen = {}
        for n, v in entries:
            seen.setdefault(v, n)
        w("/// %s" % doc)
        w("pub fn %s(v: %s) -> Option<&'static str> {" % (name, key))
        w("    Some(match v {")
        for v in sorted(seen):
            w("        0x%x => \"%s\"," % (v, seen[v]))
        w("        _ => return None,")
        w("    })")
        w("}")
        w("")

    emit("machine", "The `EM_*` name of a machine.", machine_list)

    def by_machine(name, doc, prefix):
        entries = enum_entries(elf_h, prefix)
        generic = [(n, v) for n, v in entries if not any(n.startswith(prefix + p + "_") for p in PROCESSORS)]
        specific = {}
        for n, v in entries:
            for p, ems in PROCESSORS.items():
                if n.startswith(prefix + p + "_"):
                    for em in ems:
                        specific.setdefault(em, []).append((n, v))
        w("/// %s" % doc)
        w("pub fn %s(machine: u16, v: u64) -> Option<&'static str> {" % name)
        w("    let specific = match machine {")
        for em, es in sorted(specific.items(), key=lambda x: machines.get(x[0], 0)):
            if em not in machines:
                continue
            seen = {}
            for n, v in es:
                seen.setdefault(v, n)
            arms = " ".join("0x%x => Some(\"%s\")," % (v, seen[v]) for v in sorted(seen))
            w("        0x%x => match v { %s _ => None }," % (machines[em], arms))
        w("        _ => None,")
        w("    };")
        w("    if specific.is_some() {")
        w("        return specific;")
        w("    }")
        w("    Some(match v {")
        seen = {}
        for n, v in generic:
            seen.setdefault(v, n)
        for v in sorted(seen):
            w("        0x%x => \"%s\"," % (v, seen[v]))
        w("        _ => return None,")
        w("    })")
        w("}")
        w("")

    by_machine("section_type", "The `SHT_*` name of a section type, on `machine`.", "SHT_")
    by_machine("segment_type", "The `PT_*` name of a segment type, on `machine`.", "PT_")

    # Section flags: (name, bit), generic and by machine.
    def flags(name, doc, prefix):
        entries = [(n, v) for n, v in enum_entries(elf_h, prefix) if v and (v & (v - 1)) == 0]
        generic = [(n, v) for n, v in entries if not any(n.startswith(prefix + p + "_") for p in PROCESSORS)]
        w("/// %s" % doc)
        w("pub fn %s(machine: u16) -> Vec<(&'static str, u64)> {" % name)
        w("    let mut out = vec![%s];" % ", ".join("(\"%s\", 0x%x)" % (n, v) for n, v in generic))
        w("    match machine {")
        specific = {}
        for n, v in entries:
            for p, ems in PROCESSORS.items():
                if n.startswith(prefix + p + "_"):
                    for em in ems:
                        specific.setdefault(em, []).append((n, v))
        for em, es in sorted(specific.items(), key=lambda x: machines.get(x[0], 0)):
            if em not in machines:
                continue
            w("        0x%x => out.extend([%s])," % (machines[em], ", ".join("(\"%s\", 0x%x)" % (n, v) for n, v in es)))
        w("        _ => {}")
        w("    }")
        w("    out")
        w("}")
        w("")

    flags("section_flags", "The `SHF_*` flags of sections on `machine`, by bit.", "SHF_")

    # Dynamic tags.
    dyn = open(os.path.join(inc, "DynamicTags.def"), encoding="utf-8").read()
    generic, specific = [], {}
    for m in re.finditer(r"^([A-Z0-9_]*?)_?DYNAMIC_TAG\(\s*([A-Za-z0-9_]+)\s*,\s*(0[xX][0-9A-Fa-f]+|\d+)\s*\)", dyn, re.M):
        arch, n, v = m.group(1), m.group(2), int(m.group(3), 0)
        if arch in ("", "DYNAMIC"):
            generic.append((n, v))
        else:
            ems = {"AARCH64": ["EM_AARCH64"], "HEXAGON": ["EM_HEXAGON"], "MIPS": ["EM_MIPS"], "PPC": ["EM_PPC"], "PPC64": ["EM_PPC64"], "RISCV": ["EM_RISCV"], "SPARC": ["EM_SPARC", "EM_SPARCV9"]}.get(arch, [])
            for em in ems:
                specific.setdefault(em, []).append((n, v))
    w("/// The name of a dynamic tag (`DT_` left out, as llvm-readobj prints it),")
    w("/// on `machine`.")
    w("pub fn dynamic_tag(machine: u16, v: u64) -> Option<&'static str> {")
    w("    let specific = match machine {")
    for em, es in sorted(specific.items(), key=lambda x: machines.get(x[0], 0)):
        if em not in machines:
            continue
        seen = {}
        for n, v in es:
            seen.setdefault(v, n)
        w("        0x%x => match v { %s _ => None }," % (machines[em], " ".join("0x%x => Some(\"%s\")," % (v, seen[v]) for v in sorted(seen))))
    w("        _ => None,")
    w("    };")
    w("    if specific.is_some() {")
    w("        return specific;")
    w("    }")
    w("    Some(match v {")
    seen = {}
    for n, v in generic:
        seen.setdefault(v, n)
    for v in sorted(seen):
        w("        0x%x => \"%s\"," % (v, seen[v]))
    w("        _ => return None,")
    w("    })")
    w("}")
    w("")

    # Relocation types.
    rdir = os.path.join(inc, "ELFRelocs")
    w("/// The `R_*` name of relocation type `v` on `machine`.")
    w("pub fn relocation(machine: u16, v: u32) -> Option<&'static str> {")
    w("    match machine {")
    for ems, f in RELOCS:
        text = open(os.path.join(rdir, f), encoding="utf-8").read()
        seen = {}
        for m in re.finditer(r"^ELF_RELOC\(\s*([A-Za-z0-9_]+)\s*,\s*(0x[0-9A-Fa-f]+|\d+)\s*\)", text, re.M):
            seen.setdefault(int(m.group(2), 0), m.group(1))
        values = " | ".join("0x%x" % machines[e] for e in ems if e in machines)
        if not values:
            continue
        w("        %s => Some(match v {" % values)
        for v in sorted(seen):
            w("            0x%x => \"%s\"," % (v, seen[v]))
        w("            _ => return None,")
        w("        }),")
    w("        _ => None,")
    w("    }")
    w("}")
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
