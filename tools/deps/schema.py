"""Writes schema.c: an apisetschema.dll whose .apiset section is a version 6
API set schema (as Windows 10 and later have it) for the dependency test:
api-ms-win-test-l1-1-0 hosted by apihost.dll, ext-ms-win-test-l1-1-0 by
nothing.

usage: schema.py <schema.c>
"""
import struct
import sys

SETS = [
    ("api-ms-win-test-l1-1-0", "api-ms-win-test-l1-1", ["apihost.dll"]),
    ("ext-ms-win-test-l1-1-0", "ext-ms-win-test-l1-1", []),
]


def schema():
    header = 28
    entries = header
    values = entries + 24 * len(SETS)
    strings = values + 20 * sum(len(h) for _, _, h in SETS)
    blob = bytearray()

    def text(s):
        at = strings + len(blob)
        blob.extend(s.encode("utf-16-le"))
        return at, len(s) * 2

    e = bytearray()
    v = bytearray()
    value_at = values
    for name, hashed, hosts in SETS:
        no, nl = text(name)
        e += struct.pack("<6I", 0, no, nl, len(hashed) * 2, value_at, len(hosts))
        for h in hosts:
            ho, hl = text(h)
            v += struct.pack("<5I", 0, 0, 0, ho, hl)
            value_at += 20
    out = struct.pack("<7I", 6, 0, 0, len(SETS), entries, 0, 0) + e + v + blob
    return out


data = schema()
with open(sys.argv[1], "w") as f:
    f.write("/* Generated by schema.py: the dependency test's API set schema. */\n")
    f.write('#pragma section(".apiset", read)\n')
    f.write('__declspec(allocate(".apiset")) const unsigned char schema[] = {\n')
    for i in range(0, len(data), 16):
        f.write("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",\n")
    f.write("};\n")
