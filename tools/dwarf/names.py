"""Generates crates/symbols/dwarf/src/spelling.rs's tables: the names
llvm-dwarfdump prints for DWARF's constants (DW_TAG_compile_unit,
DW_LANG_C_plus_plus_14, ...), from LLVM's Dwarf.def and Dwarf.h (Apache
License 2.0 with LLVM Exceptions; see crates/symbols/dwarf/LICENSE-LLVM).

    python -I tools/dwarf/names.py <llvm-project> > crates/symbols/dwarf/src/spelling.rs
"""

import os
import re
import sys

# Dwarf.def's macros: (macro, prefix, the Rust function's name).
GROUPS = [
    ("HANDLE_DW_TAG", "DW_TAG_", "tag"),
    ("HANDLE_DW_AT", "DW_AT_", "attribute"),
    ("HANDLE_DW_FORM", "DW_FORM_", "form"),
    ("HANDLE_DW_OP", "DW_OP_", "operation"),
    ("HANDLE_DW_LANG", "DW_LANG_", "language"),
    ("HANDLE_DW_ATE", "DW_ATE_", "encoding"),
    ("HANDLE_DW_VIRTUALITY", "DW_VIRTUALITY_", "virtuality"),
    ("HANDLE_DW_DEFAULTED", "DW_DEFAULTED_", "defaulted"),
    ("HANDLE_DW_CC", "DW_CC_", "calling_convention"),
    ("HANDLE_DW_RLE", "DW_RLE_", "range_list_entry"),
    ("HANDLE_DW_LLE", "DW_LLE_", "location_list_entry"),
    ("HANDLE_DW_UT", "DW_UT_", "unit_type"),
    ("HANDLE_DW_IDX", "DW_IDX_", "index_attribute"),
    ("HANDLE_DW_END", "DW_END_", "endianity"),
    ("HANDLE_DW_LNS", "DW_LNS_", "line_standard"),
    ("HANDLE_DW_LNE", "DW_LNE_", "line_extended"),
    ("HANDLE_DW_LNCT", "DW_LNCT_", "line_content"),
    ("HANDLE_DW_MACRO", "DW_MACRO_", "macro_entry"),
    ("HANDLE_DW_MACRO_GNU", "DW_MACRO_GNU_", "macro_gnu_entry"),
    ("HANDLE_DW_CFA", "DW_CFA_", "call_frame"),
    ("HANDLE_DW_SECT", "DW_SECT_", "section_kind"),
    ("HANDLE_DW_APPLE_PROPERTY", "DW_APPLE_PROPERTY_", "apple_property"),
]

# Dwarf.h's enums of names not in Dwarf.def.
H_ENUMS = [
    ("DW_ACCESS_", "accessibility"),
    ("DW_VIS_", "visibility"),
    ("DW_INL_", "inline"),
    ("DW_ID_", "identifier_case"),
    ("DW_ORD_", "array_ordering"),
    ("DW_DSC_", "discriminant"),
    ("DW_CHILDREN_", "children"),
]


def main():
    root = sys.argv[1]
    inc = os.path.join(root, "llvm", "include", "llvm", "BinaryFormat")
    with open(os.path.join(inc, "Dwarf.def"), encoding="utf-8") as f:
        text = f.read()
    with open(os.path.join(inc, "Dwarf.h"), encoding="utf-8") as f:
        header = f.read()
    out = []
    w = out.append
    w("//! The names llvm-dwarfdump gives DWARF's constants (`DW_TAG_compile_unit`,")
    w("//! `DW_LANG_C_plus_plus_14`, ...), by group.")
    w("//!")
    w("//! Generated by tools/dwarf/names.py from LLVM's Dwarf.def and Dwarf.h")
    w("//! (Apache License 2.0 with LLVM Exceptions: see LICENSE-LLVM). Do not edit.")
    w("")
    for macro, prefix, fn in GROUPS:
        seen = {}
        for m in re.finditer(r"^%s\(\s*(0x[0-9A-Fa-f]+|\d+)\s*,\s*([A-Za-z0-9_]+)" % re.escape(macro), text, re.M):
            value = int(m.group(1), 0)
            seen.setdefault(value, prefix + m.group(2))
        emit(w, fn, prefix, seen)
    # Each language's default lower bound for arrays (Dwarf.def's
    # LOWER_BOUND: 0 or 1; absent for languages it doesn't know).
    bounds = {}
    for m in re.finditer(r"^HANDLE_DW_LANG\(\s*(0x[0-9A-Fa-f]+|\d+)\s*,\s*[A-Za-z0-9_]+\s*,\s*(\d+)", text, re.M):
        bounds.setdefault(int(m.group(1), 0), int(m.group(2)))
    w("/// A language's default lower bound for arrays (`DW_LANG_*`), as LLVM")
    w("/// knows it.")
    w("pub fn language_lower_bound(v: u64) -> Option<u64> {")
    w("    Some(match v {")
    for value in sorted(bounds):
        w("        0x%x => %d," % (value, bounds[value]))
    w("        _ => return None,")
    w("    })")
    w("}")
    w("")
    for prefix, fn in H_ENUMS:
        seen = {}
        for m in re.finditer(r"^\s*(%s[A-Za-z0-9_]+)\s*=\s*(0x[0-9A-Fa-f]+|\d+)\s*,?" % re.escape(prefix), header, re.M):
            seen.setdefault(int(m.group(2), 0), m.group(1))
        emit(w, fn, prefix, seen)
    sys.stdout.write("\n".join(out) + "\n")


def emit(w, fn, prefix, names):
    w("/// The `%s*` name of `v`, as llvm-dwarfdump prints it." % prefix)
    w("pub fn %s(v: u64) -> Option<&'static str> {" % fn)
    w("    Some(match v {")
    for value in sorted(names):
        w("        0x%x => \"%s\"," % (value, names[value]))
    w("        _ => return None,")
    w("    })")
    w("}")
    w("")


if __name__ == "__main__":
    main()
