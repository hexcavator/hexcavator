/// The instruction with this prefix (0 for none) and opcode.
pub fn lookup(prefix: u8, code: u32) -> Option<&'static Op> {
    OPS.binary_search_by(|o| (o.prefix, o.code).cmp(&(prefix, code)))
        .ok()
        .map(|i| &OPS[i])
}

/// The prefixes of multi-byte opcodes.
pub fn is_prefix(byte: u8) -> bool {
    matches!(byte, 0xFB..=0xFE)
}
