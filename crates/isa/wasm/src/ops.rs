//! The WebAssembly instruction set: every opcode's name and the kind of
//! immediates that follow it, from the WebAssembly specification (2.0,
//! plus the proposals now in browsers and toolchains: exception handling,
//! tail calls, typed function references, GC, threads, relaxed SIMD, half
//! precision, wide arithmetic, multiple memories).

/// What follows an opcode.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Kind {
    /// Nothing.
    None,
    /// A block type: empty, one value type, or a type index.
    Block,
    /// A label (a branch depth).
    Label,
    /// A list of labels and a default.
    BrTable,
    /// A function index.
    Func,
    /// A type index and a table index.
    CallIndirect,
    /// A type index.
    Type,
    /// A tag index.
    Tag,
    /// A list of value types (typed `select`).
    SelectT,
    /// A block type and a list of catch clauses.
    TryTable,
    /// A local index.
    Local,
    /// A global index.
    Global,
    /// A table index.
    Table,
    /// A memory argument: alignment (with a memory index if bit 6 is
    /// set) and offset.
    MemArg,
    /// A memory argument and a lane index.
    MemArgLane,
    /// A memory index.
    Memory,
    /// A lane index.
    Lane,
    /// A signed 32-bit integer.
    I32,
    /// A signed 64-bit integer.
    I64,
    /// A 32-bit float.
    F32,
    /// A 64-bit float.
    F64,
    /// Sixteen bytes.
    V128,
    /// Sixteen lane indexes.
    Shuffle,
    /// A data segment index and a memory index.
    MemoryInit,
    /// A data segment index.
    Data,
    /// Two memory indexes (destination, source).
    MemoryCopy,
    /// Two table indexes (destination, source).
    TableCopy,
    /// An element segment index and a table index.
    TableInit,
    /// An element segment index.
    Elem,
    /// A heap type.
    HeapType,
    /// A heap type, nullable (`ref.test (ref null t)`).
    NullHeapType,
    /// A reserved byte (`atomic.fence`).
    Fence,
    /// A type index and a field index.
    TypeField,
    /// Two type indexes.
    TypeType,
    /// A type index and a data segment index.
    TypeData,
    /// A type index and an element segment index.
    TypeElem,
    /// A type index and a count.
    TypeN,
    /// Flags, a label, and two heap types.
    BrOnCast,
}

/// An instruction: its prefix (0 for none) and opcode, name, and
/// immediates.
#[derive(Clone, Copy, Debug)]
pub struct Op {
    /// Its prefix byte (0 for none).
    pub prefix: u8,
    /// Its opcode (after the prefix, LEB128-decoded).
    pub code: u32,
    /// Its name.
    pub name: &'static str,
    /// Its immediates' kind.
    pub kind: Kind,
}

const fn op(prefix: u8, code: u32, name: &'static str, kind: Kind) -> Op {
    Op {
        prefix,
        code,
        name,
        kind,
    }
}

