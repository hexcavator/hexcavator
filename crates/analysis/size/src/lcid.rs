/// The display name of language `lcid`, as SizeBench shows it.
pub(crate) fn language_name(lcid: u16) -> &'static str {
    if lcid == 0 || lcid == 0x400 {
        return "LANG_NEUTRAL";
    }
    match LANGUAGES.binary_search_by_key(&lcid, |&(id, _)| id) {
        Ok(i) => LANGUAGES[i].1,
        Err(_) => "Unknown language",
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn names() {
        assert!(LANGUAGES.windows(2).all(|w| w[0].0 < w[1].0));
        assert_eq!(language_name(0x409), "English (United States)");
        assert_eq!(language_name(0x809), "English (United Kingdom)");
        assert_eq!(language_name(0x411), "Japanese (Japan)");
        assert_eq!(language_name(0), "LANG_NEUTRAL");
        assert_eq!(language_name(0x400), "LANG_NEUTRAL");
        assert_eq!(language_name(0x800), "Unknown language");
    }
}
